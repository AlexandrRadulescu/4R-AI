def build_backbone(name: str):

    if name == "resnet18":
        net = models.resnet18(weights = models.ResNet18_Weights.IMAGENET1K_V1)
        dim = net.fc.in_features
        net.fc = nn.Identity()
    else: 
        raise SystemExit(f"Unknown backbone name {name}!")
    net.eval()

    for p in net.parameters():
        p.requires_grad = False
    return net, dim


class ImageList(torch.utils.data.Dataset):
    def __init__(self, paths, labels, transform):
        self.paths = paths
        self.labels = labels
        self.transform = transform

    def __len__(self):
        return len(self.paths)

    def __getitem__(self, index):
        with Image.open(self.paths[index]) as im:
            return self.transform(im.convert("RGB")), self.labels[index]


def make_dataset(paths, labels, img_size):
    tf = transforms.Compose([
        transforms.Resize(int(img_size * 1.14)),
        transforms.CenterCrop(img_size),
        transforms.ToTensor(),
        transforms.Normalize([0.485, 0.456, 0.406], [0.229, 0.224, 0.225]),
    ])
    return ImageList(paths, labels, tf)


def cmd_extract(args):

    torch.set_num_threads(args.threads or torch.get_num_threads())
    print(f"torch {torch.__version__} | threads = {torch.get_num_threads()}")

    print(f"\nIndexing {args.data_dir}...")

    paths, labels, class_names = index_images(Path(args.data_dir), args.limit_per_class, args.seed)

    print(f"    total {len(paths)} images, {len(class_names)} classes ")

    print(f"Loading Backbone {args.backbone} ...")
    net, dim = build_backbone(args.backbone)

    print(f"    feature dimention: {dim}")

    loader = torch.utils.data.DataLoader(
        make_dataset(paths, labels, args.img_size),
        batch_size= args.batch_size, 
        shuffle = False,
        num_workers= args.workers,
        drop_last=False,
    )

    feats = np.zeros((len(paths), dim), dtype = np.float32)
    t0 = time.time()
    done = 0

    with torch.inference_mode(): # No autograd graph -> faster
        for x, _ in loader:
            out = net(x).cpu().numpy()
            feats[done:done + len(out)] = out

            done += len(out)

            rate = done / (time.time() - t0)

            eta = (len(paths) - done) / max(rate, 1e-9)

            print(f"\r {done} / {len(paths)} {rate:5.1f} img/s eta {eta/60:4.1f} min", end="", flush=True)

    print(f"\nDone in {(time.time() - t0)/60:.1f} min")

    np.savez_compressed(
        args.out,
        features = feats,
        labels = labels,
        paths = np.asarray(paths),
        class_names = np.asarray(class_names),
        meta = json.dumps({"backbone": args.backbone, "img_size": args.img_size}),
    )

    print(f"Saved {args.out} ({Path(args.out).stat().st_size/1e6:.1f} MB)")
    print(f"\nNext: python {Path(sys.argv[0]).name} train --features {args.out}")

        ## Stage 2: Train + Evaluate Classifier

def make_classifier(C = 1.0):
    return make_pipeline(
        StandardScaler(),
        LogisticRegression(C=C, max_iter = 3000),
    )

def print_confusion(cm, class_names):
    w = max(len(n) for n in class_names)

    header = "true // pred".rjust(w)
    print("\n" + header + " " + " ".join(f"{n[:8]:>8s}" for n in class_names))
    for i, name in enumerate(class_names):
        row = " ".join(f"{v:8d}" for v in cm[i])
        print(f"{name:>{w}} {row}   ({cm[i,i] / max(cm[i].sum(), 1):.1%} recall)")

def cmd_train(args):
    d = np.load(args.features, allow_pickle=False)
    X,y = d["features"], d["labels"]
    class_names = [str(s) for s in d["class_names"]]
    meta = json.loads(str(d["meta"]))

    print(f"Features: {X.shape[0]} samples x {X.shape[1]} dims (backbone = {meta['backbone']})")
    print("Class balance: ", dict(zip(class_names, np.bincount(y).tolist())))


    # ------------------------------------------------------------- LOADED

    Xtr, Xte, ytr, yte = train_test_split(
        X, y, test_size=args.test_size, stratify=y , random_state=args.seed
    )

    clf = make_classifier(args.C)
    t0 =  time.time()
    clf.fit(Xtr, ytr)
    train_acc = accuracy_score(ytr, clf.predict(Xtr))
    test_acc  = accuracy_score(yte, clf.predict(Xte))
    print(f"\n \t Random 80/20 tts: ({time.time()-t0:.1f}s to fit)")
    print(f"train accuracy : {train_acc:.4f}")
    print(f"test accuracy : {test_acc:.4f}")
    print(f"gap     : {train_acc - test_acc:.4f} overfitting measurement")
    print(classification_report(yte, clf.predict(Xte), target_names=class_names, digits = 4))

    print_confusion(confusion_matrix(yte, clf.predict(Xte)), class_names)

    # --------------------------------------------------------------- Is the no stable or lucky split?

    cv = cross_val_score(make_classifier(args.C), X, y, cv = StratifiedKFold(
        5, shuffle=True, random_state=args.seed), n_jobs=1
    )

    print(f"\n 5-fold stratified CV {cv.round(4)} mean {cv.mean():.4f} +/- {cv.std():.4f}")

    if args.audit:
        # -------leakage audit

        print("Leakage audit: grouped split")

        groups = np.zeros(len(y), dtype = np.int64)
        next_gid = 0
        for c in np.unique(y):
            idx = np.flatnonzero(y == c)
            k = max(2, len(idx) // AUGS_PER_ORIGINAL)
            Xn = X[idx] / (np.linalg.norm(X[idx], axis=1, keepdims=True) + 1e-9)

            km = MiniBatchKMeans(
                n_clusters=k,
                random_state=args.seed,
                n_init=3,
                batch_size=1024
            )

            groups[idx] = km.fit_predict(Xn) + next_gid

            next_gid += k

            print(f"  {class_names[c]:10s} -> {k} approximate slide groups")

        min_groups = min(len(np.unique(groups[y == c])) for c in np.unique(y))

        if min_groups < 10:
            print(f"  [skipped] only {min_groups} groups in the smallest class -- the grouped", 
                  "\n   folds would be degenerate. Run this on the full dataset,",
                  "\n   or with --limit-per-class 500 or more.")
        else:
            gscores = cross_val_score(make_classifier(args.C), X, y, groups=groups, 
                                      cv = StratifiedGroupKFold(5, shuffle=True, random_state=args.seed), n_jobs = 1)
            print(f"  grouped 5-fold: {gscores.round(4)}  mean {gscores.mean():.4f}",
                f"\n  random  5-fold: mean {cv.mean():.4f}",
                f"\n optimism from near-duplicate leakage: {cv.mean() - gscores.mean():+.4f}",
                "\n ^ trust the grouped number as your real-world estimate")

        print("Learning Curve: ")

        for frac in (0.05, 0.15, 0.35, 0.65, 1.0):
            n = max(len(class_names) * 5, int(len(Xtr) * frac))
            sub = np.random.default_rng(args.seed).choice(len(Xtr),n ,replace=False)

            m = make_classifier(args.C).fit(Xtr[sub], ytr[sub])

            print(f"n={n:6d}  test acc {accuracy_score(yte, m.predict(Xte)):.4f}")


        # Sanity check

        if args.audit:
            rng = np.random.default_rng(args.seed)
            y_shuf = rng.permutation(ytr)
            m = make_classifier(args.C).fit(Xtr, y_shuf)

            print(f"\nShuffled-label control: {accuracy_score(yte, m.predict(Xte)):.4f} "
              f"(chance = {1/len(class_names):.4f}) -- if this is high, there's a bug.")


    if args.model_out:
        
        joblib.dump({"clf": clf, "class_names": class_names, "meta": meta}, args.model_out)
        print(f"\nSaved model -> {args.model_out}")



    ## Stage 3: Predict on new image

def cmd_predict(args):

    bundle = joblib.load(args.model)
    net, _ = build_backbone(bundle["meta"]["backbone"])
    ds = make_dataset([args.image], np.zeros(1, dtype = np.int64), bundle["meta"]["img_size"])

    with torch.inference_mode():
        feat = net(ds[0][0].unsqueeze(0)).cpu().numpy()

    proba = bundle["clf"].predict_proba(feat)[0]

    order = np.argsort(proba)[::-1]

    print(f"\n{Path(args.image).name}")
    for i in order:
        print(f"  {bundle['class_names'][i]:10s} {proba[i]:7.2%}  {CLASS_DIRS.get(bundle['class_names'][i], '')}")


