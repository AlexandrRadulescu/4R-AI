def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest = "cmd", required=True)

    e = sub.add_parser("extract", help="run images through the frozen backbone, cache features")

    e.add_argument("--data-dir", required=True, help="folder containing the 5 class subfolders")
    e.add_argument("--out", default="features.npz")
    e.add_argument("--backbone", default="resnet18",
                   choices=["resnet18", "resnet50", "mobilenet_v3_large"])
    e.add_argument("--img-size", type=int, default=224)
    e.add_argument("--batch-size", type=int, default=32)
    e.add_argument("--workers", type=int, default=4, help="image-loading processes; 0 if Windows complains")
    e.add_argument("--threads", type=int, default=0, help="torch CPU threads (0 = auto)")
    e.add_argument("--limit-per-class", type=int, default=None, help="use a random subset, for quick trials")
    e.add_argument("--seed", type=int, default=42)
    e.set_defaults(func=cmd_extract)

    t = sub.add_parser("train", help="fit + evaluate the classifier on cached features")
    t.add_argument("--features", default="features.npz")
    t.add_argument("--test-size", type=float, default=0.2)
    t.add_argument("--C", type=float, default=1.0, help="inverse regularisation strength")
    t.add_argument("--audit", action="store_true", help="run the leakage + sanity checks")
    t.add_argument("--model-out", default=None)
    t.add_argument("--seed", type=int, default=42)
    t.set_defaults(func=cmd_train)
 
    p = sub.add_parser("predict", help="classify a single image")
    p.add_argument("--model", required=True)
    p.add_argument("--image", required=True)
    p.set_defaults(func=cmd_predict)
 
    args = ap.parse_args()
    args.func(args)

if __name__ == "__main__":
    main()