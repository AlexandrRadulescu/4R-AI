CLASS_DIRS = {
    "colon_aca": "colon adenocarcinoma",
    "colon_n": "colon benign",
    "lung_aca": "lung adenocarcinoma",
    "lung_n" : "lung benign",
    "lung_scc": "lung squamos cell carcinoma",
}

IMG_EXT = {".jpeg", ".jpg", ".png", ".tif", ".tiff", ".bmp"}


AUGS_PER_ORIGINAL = 20 #images were generated by flipping and rotating the same images so its ~20 per original image


def find_class_dirs(root: Path) -> dict[str, Path]:
    found: dict[str, Path] = {}
    for path in [root, *root.rglob("*")]:
        if path.is_dir() and path.name in CLASS_DIRS and path.name not in found:
            found[path.name] = path

    missing = set(CLASS_DIRS) - set(found)
    if missing:
        raise SystemExit( f"Could not find class folder(s) {sorted(missing)} under {root}.\n"
            f"Expected subfolders named: {sorted(CLASS_DIRS)}\n"
            f"Found instead: {sorted(found) or 'nothing'}")

    return found

def index_images(root: Path, limit_per_class: int | None, seed: int):
    dirs = find_class_dirs(root)
    class_names = sorted(dirs)
    rng = np.random.default_rng(seed)

    paths: list[str] = []
    labels: list[int] = []
    for idx, name in enumerate(class_names):
        files = sorted(p for p in dirs[name].iterdir() if p.suffix.lower() in IMG_EXT)
        if not files:
            raise SystemExit(f"No images in {dirs[name]}")

        if limit_per_class and len(files) > limit_per_class:
            files = [files[i] for i in sorted(rng.choice(len(files), limit_per_class, replace=False))]
            paths += [str(p) for p in files]

            labels += [idx] * len(files)
            print(f" {name:.10s} {len(files):6d} images ({CLASS_DIRS[name]})")


    return paths, np.asarray(labels, dtype=np.int64), class_names


